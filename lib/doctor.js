#!/usr/bin/env node
"use strict";
// signoff doctor — one command that answers "why didn't the guard do what I expected?".
//
// Every check is read-only: the doctor never installs, rewrites or deletes anything. It
// composes the commands that already exist (`status`, `audit`, `p4 verify`) instead of
// re-deriving their logic, so a doctor that says `ok` and a gate that runs later cannot
// disagree about what "installed" or "missing" means.

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const core = require("./core");
const p4 = require("./p4");

const DISPATCHER = path.join(__dirname, "..", "bin", "signoff.js");
const STATE = ".signoff";
const HOOK_MARK = "# generated by dsh-signoff";
const STAGES = ["pre-commit", "commit-msg", "pre-push"];

const USAGE = `usage: signoff doctor [-h] [--json] [--quiet]

Why is (or isn't) this repo guarded? Read-only: nothing is installed, changed or deleted.

options:
  -h, --help   show this help message and exit
  --json       machine-readable result
  --quiet      only print checks that are not ok
`;

function cli(args) {
  const r = spawnSync(process.execPath, [DISPATCHER, ...args], { encoding: "utf8" });
  return { code: r.status === null ? 127 : r.status, out: (r.stdout || "").trim(), err: (r.stderr || "").trim() };
}

function readJson(p) {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch (e) {
    return null;
  }
}

function onPath(exe) {
  const dirs = (process.env.PATH || "").split(path.delimiter).filter(Boolean);
  const names = process.platform === "win32" ? [`${exe}.cmd`, `${exe}.ps1`, `${exe}.exe`, exe] : [exe];
  for (const d of dirs) {
    for (const n of names) {
      if (fs.existsSync(path.join(d, n))) return path.join(d, n);
    }
  }
  return "";
}

function repoTop() {
  const r = core.git(["rev-parse", "--show-toplevel"]);
  return r.code === 0 ? r.out.trim() : "";
}

function run(argv) {
  const args = core.parseArgs(argv || [], {});
  if (args.help || args._.indexOf("-h") !== -1) {
    console.log(USAGE);
    return 0;
  }
  const asJson = !!args.json;
  const quiet = !!args.quiet;

  const checks = [];
  const add = (id, status, detail, fix) => checks.push({ id, status, detail, fix: fix || "" });

  // --- environment (the old `doctor` rows, now with verdicts) -----------------
  const major = Number(process.version.replace(/^v/, "").split(".")[0]);
  add("node", major >= 18 ? "ok" : "fail", process.version, major >= 18 ? "" : "install Node 18 or newer");
  const gitBin = onPath("git");
  add("git", gitBin ? "ok" : "fail", gitBin || "not on PATH", gitBin ? "" : "install git and put it on PATH");
  const engine = process.env.SIGNOFF_ENGINE === "python" ? "python" : "node";
  add("engine", "ok", engine);

  const top = repoTop();
  if (!top || core.git(["rev-parse", "--git-dir"]).code !== 0) {
    add("repo", "fail", process.cwd(), "run inside a git repository");
    return report(checks, asJson, quiet, 2);
  }
  add("repo", "ok", top);

  // --- installation -----------------------------------------------------------
  const st = readJsonOr(() => JSON.parse(cli(["status", "--json"]).out), null);
  const version = st && st.version ? st.version : "";
  add("version", version ? "ok" : "warn", version || "unknown", version ? "" : "reinstall: npm i -g dsh-signoff");

  const hooksDir = path.join(top, ".git", "hooks");
  for (const stage of STAGES) {
    const p = path.join(hooksDir, stage);
    const exists = fs.existsSync(p);
    const ours = exists && fs.readFileSync(p, "utf8").indexOf(HOOK_MARK) !== -1;
    if (!ours) {
      add(`hook:${stage}`, "fail", exists ? "a foreign hook is there" : "missing", "run: signoff init");
      continue;
    }
    let mode = "ok";
    if (process.platform !== "win32") {
      if ((fs.statSync(p).mode & 0o111) === 0) mode = "fail";
    }
    add(`hook:${stage}`, mode, mode === "ok" ? "installed" : "not executable", mode === "ok" ? "" : `chmod +x ${p}`);
    const backup = path.join(hooksDir, `${stage}.signoff-backup`);
    if (fs.existsSync(backup)) {
      add(`hook-backup:${stage}`, "warn", "old hook saved, not chained", "wire it manually or rerun init after moving it");
    }
  }

  const hookText = fs.existsSync(path.join(hooksDir, "pre-commit"))
    ? fs.readFileSync(path.join(hooksDir, "pre-commit"), "utf8")
    : "";
  const resolvable = onPath("signoff");
  if (hookText && hookText.indexOf("signoff") !== -1) {
    add(
      "hook:path",
      resolvable ? "ok" : "warn",
      resolvable || "signoff not on PATH for non-interactive shells",
      resolvable ? "" : "hooks that call `signoff` fail silently when PATH differs; reinstall globally"
    );
  }
  // --- configuration ----------------------------------------------------------
  const cfgPath = path.join(top, STATE, "config.json");
  const cfg = fs.existsSync(cfgPath) ? readJson(cfgPath) : null;
  if (!cfg) {
    add("config", fs.existsSync(cfgPath) ? "fail" : "warn", fs.existsSync(cfgPath) ? "unreadable" : "missing", "run: signoff init");
  } else {
    const bad = [];
    if (typeof cfg.version !== "number") bad.push("version");
    if (cfg.docs !== undefined && !Array.isArray(cfg.docs)) bad.push("docs");
    if (cfg.test_cmd !== undefined && cfg.test_cmd !== null && typeof cfg.test_cmd !== "string") bad.push("test_cmd");
    if (cfg.budget !== undefined && !(typeof cfg.budget === "number" && cfg.budget > 0)) bad.push("budget");
    add("config", bad.length ? "fail" : "ok", bad.length ? `bad field(s): ${bad.join(", ")}` : JSON.stringify(cfg).slice(0, 80), bad.length ? "fix or delete .signoff/config.json, then rerun signoff init" : "");
    if (typeof cfg.test_cmd === "string" && cfg.test_cmd) {
      const exe = cfg.test_cmd.split(/\s+/)[0];
      const found = exe.includes(path.sep) || exe.includes("/") ? fs.existsSync(path.join(top, exe)) : !!onPath(exe);
      add("test-cmd", found ? "ok" : "warn", cfg.test_cmd, found ? "" : "p1 will fail to start it; check the command or PATH");
    }
  }

  // --- install point ----------------------------------------------------------
  const ipPath = path.join(top, STATE, "installed.json");
  const ip = fs.existsSync(ipPath) ? readJson(ipPath) : null;
  if (!ip || !ip.sha) {
    add("install-point", "warn", "not recorded", "run: signoff init (records it; re-init keeps the first)");
  } else if (core.git(["cat-file", "-e", `${ip.sha}^{commit}`]).code !== 0) {
    add("install-point", "fail", `${ip.sha.slice(0, 12)} not in history (rewritten?)`, "reinstall after the rewrite: signoff init");
  } else {
    add("install-point", "ok", `${ip.sha.slice(0, 12)} (${ip.ts || "no ts"})`);
  }
  if (ip && ip.version && version && ip.version !== version) {
    add("install-version", "warn", `installed ${ip.version}, CLI ${version}`, "upgrade in place: npm i -g dsh-signoff && signoff init");
  }

  // --- leftover state ---------------------------------------------------------
  const marker = path.join(top, STATE, "passed");
  if (fs.existsSync(marker)) {
    const m = readJson(marker);
    add("marker", "warn", `leftover ${m && m.mode ? m.mode : "?"} record`, "a commit was interrupted; the next pre-commit overwrites it");
  } else {
    add("marker", "ok", "none");
  }
  const skipsPath = path.join(top, STATE, "skips.log");
  if (fs.existsSync(skipsPath)) {
    const n = fs.readFileSync(skipsPath, "utf8").split(/\r?\n/).filter(Boolean).length;
    add("skips", "warn", `${n} recorded skip(s)`, "inspect: .signoff/skips.log; audit --strict fails on them");
  } else {
    add("skips", "ok", "none");
  }

  // --- ledger -----------------------------------------------------------------
  const ledger = p4.ledgerPath();
  if (!fs.existsSync(ledger)) {
    add("ledger", "ok", "empty (nothing recorded yet)");
  } else {
    let entries = [];
    try {
      entries = p4.entries();
    } catch (e) {
      add("ledger", "fail", "unreadable", "inspect or move it away, then re-record");
    }
    const key = p4.repoKey();
    const foreign = entries.filter((e) => e && e.repo && key && e.repo !== key).length;
    const v = readJsonOr(() => JSON.parse(cli(["p4", "verify", "--json"]).out), null);
    if (!v) {
      add("ledger", "fail", "verify did not return JSON", "run: signoff p4 verify");
    } else {
      add(
        "ledger",
        v.ok ? (foreign ? "warn" : "ok") : "fail",
        `${entries.length} entries, ${foreign} from other repos${v.problems && v.problems.length ? `, ${v.problems.length} problem(s)` : ""}`,
        v.ok ? "" : "the chain is broken or a rollback point is gone; inspect .signoff/audit.log"
      );
      for (const p of (v.problems || []).slice(0, 3)) add("ledger:problem", "fail", String(p));
    }
  }

  // --- what actually landed ----------------------------------------------------
  const audit = readJsonOr(() => {
    const r = cli(["audit", "--since-install", "--json"]);
    return r.out ? JSON.parse(r.out) : null;
  }, null);
  if (!audit) {
    add("audit", "warn", "--since-install unavailable (no install point)", "signoff audit --range A..B");
  } else {
    const c = audit.counts || {};
    add(
      "audit",
      c.missing ? "fail" : c.skip ? "warn" : "ok",
      `pass=${c.pass || 0} skip=${c.skip || 0} missing=${c.missing || 0}`,
      c.missing ? "commits without a trailer: they bypassed the hook (--no-verify) or predate the install point" : ""
    );
  }

  return report(checks, asJson, quiet, checks.some((c) => c.status === "fail") ? 1 : 0);
}

function readJsonOr(fn, fallback) {
  try {
    return fn();
  } catch (e) {
    return fallback;
  }
}

function report(checks, asJson, quiet, code) {
  const fails = checks.filter((c) => c.status === "fail").length;
  const warns = checks.filter((c) => c.status === "warn").length;
  if (asJson) {
    core.json({ ok: fails === 0, fails, warns, checks });
    return code;
  }
  for (const c of checks) {
    if (quiet && c.status === "ok") continue;
    console.log(`${c.status.padEnd(5)}${c.id.padEnd(20)}${c.detail}`);
    if (c.fix) console.log(`${"".padEnd(5)}${"".padEnd(20)}→ ${c.fix}`);
  }
  console.log(`doctor: ${fails ? `${fails} fail` : "no failures"}, ${warns} warning(s)`);
  return code;
}

module.exports = { run, USAGE };
